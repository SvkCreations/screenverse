import { useEffect, useRef, useState } from 'react'
import { Send, Sparkles } from 'lucide-react'
import RecommendationCard from './RecommendationCard.jsx'
import { getRecommendations } from '../services/gemini.js'
import { EXAMPLES } from '../utils/aiOptions.js'
import styles from './AIChat.module.css'

export default function AIChat() {
  const [messages, setMessages] = useState([])
  const [input, setInput] = useState('')
  const [loading, setLoading] = useState(false)
  const bottom = useRef(null)

  useEffect(() => {
    if (messages.length) bottom.current?.scrollIntoView({ behavior: 'smooth', block: 'end' })
  }, [messages, loading])

  async function send(text) {
    const msg = text.trim()
    if (!msg || loading) return
    const history = messages
      .filter((m) => m.text)
      .slice(-6)
      .map((m) => ({ role: m.role, text: m.text }))
    setMessages((m) => [...m, { role: 'user', text: msg }])
    setInput('')
    setLoading(true)
    try {
      const r = await getRecommendations({ mode: 'chat', message: msg, history })
      const text = r.message || r.strategy || 'Here’s what I found.'
      setMessages((m) => [...m, { role: 'assistant', text, items: r.items, dropped: r.dropped }])
    } catch (e) {
      setMessages((m) => [...m, { role: 'assistant', text: '', error: e.message }])
    } finally {
      setLoading(false)
    }
  }

  return (
    <div className={styles.chat}>
      {messages.length === 0 && (
        <div className={styles.intro}>
          <Sparkles size={26} />
          <p>Ask in your own words. I’ll suggest real titles and check each one in the movie database.</p>
          <div className={styles.examples}>
            {EXAMPLES.map((ex) => (
              <button key={ex} onClick={() => send(ex)} disabled={loading}>{ex}</button>
            ))}
          </div>
        </div>
      )}

      <div className={styles.thread}>
        {messages.map((m, i) =>
          m.role === 'user' ? (
            <div key={i} className={styles.user}>{m.text}</div>
          ) : (
            <div key={i} className={styles.bot}>
              {m.error ? (
                <p className={styles.error}>{m.error}</p>
              ) : (
                <>
                  <p>{m.text}</p>
                  {m.items.length === 0 ? (
                    <p className={styles.dim}>I couldn’t verify any titles for that. Try rewording your request.</p>
                  ) : (
                    <div className={styles.cards}>
                      {m.items.map((item) => <RecommendationCard key={item.imdbId} item={item} />)}
                    </div>
                  )}
                  {m.dropped > 0 && (
                    <p className={styles.dim}>
                      {m.dropped} suggestion{m.dropped === 1 ? '' : 's'} couldn’t be verified and {m.dropped === 1 ? 'was' : 'were'} hidden. “AI match” is generated by Gemini, not an official rating.
                    </p>
                  )}
                </>
              )}
            </div>
          )
        )}
        {loading && <div className={styles.bot}><p className={styles.dim}>Thinking and checking titles…</p></div>}
        <div ref={bottom} />
      </div>

      <form className={styles.form} onSubmit={(e) => { e.preventDefault(); send(input) }}>
        <input
          value={input}
          onChange={(e) => setInput(e.target.value)}
          placeholder="e.g. a slow-burn Hindi crime series"
          maxLength={500}
          aria-label="Ask for a recommendation"
        />
        <button type="submit" disabled={loading || !input.trim()} aria-label="Send"><Send size={18} /></button>
      </form>
    </div>
  )
}
