import { useState } from 'react'
import { Link } from 'react-router-dom'
import { Sparkles, Star, Bookmark } from 'lucide-react'
import { useWatchlist } from '../context/WatchlistContext.jsx'
import styles from './RecommendationCard.module.css'

export default function RecommendationCard({ item }) {
  const [broken, setBroken] = useState(false)
  const { has, toggle } = useWatchlist()
  const saved = has(item.imdbId)
  const meta = [item.year, item.type === 'series' ? 'Series' : 'Movie', item.genres.slice(0, 3).join(' / '), item.languages[0]]
    .filter(Boolean)
    .join(' · ')

  return (
    <article className={styles.card}>
      <Link to={`/title/${item.imdbId}`} className={styles.poster}>
        {item.poster && !broken ? (
          <img src={item.poster} alt={item.title} loading="lazy" onError={() => setBroken(true)} />
        ) : (
          <div className={styles.fallback}>{item.title}</div>
        )}
      </Link>
      <div className={styles.body}>
        <div className={styles.top}>
          <Link to={`/title/${item.imdbId}`} className={styles.title}>{item.title}</Link>
          <button
            className={`${styles.save} ${saved ? styles.saved : ''}`}
            onClick={() => toggle(item)}
            aria-label={saved ? 'Remove from watchlist' : 'Add to watchlist'}
          >
            <Bookmark size={18} fill={saved ? 'currentColor' : 'none'} />
          </button>
        </div>
        <p className={styles.meta}>{meta}</p>
        <div className={styles.badges}>
          {item.imdbRating && (
            <span className={styles.imdb} title="Official IMDb rating via OMDb">
              <Star size={13} fill="currentColor" /> {item.imdbRating} IMDb
            </span>
          )}
          {item.matchScore !== null && (
            <span className={styles.ai} title="Generated by AI. Not an official rating.">
              <Sparkles size={13} /> {item.matchScore}% AI match
            </span>
          )}
        </div>
        {item.plot && <p className={styles.plot}>{item.plot}</p>}
        {item.reason && (
          <p className={styles.reason}>
            <b>Why Gemini picked it</b>
            {item.reason}
          </p>
        )}
      </div>
    </article>
  )
}
