import { RefreshCw, Sparkles } from 'lucide-react'
import RecommendationCard from './RecommendationCard.jsx'
import styles from './RecommendationSection.module.css'

export default function RecommendationSection({ strategy, items, dropped, onRegenerate, loading }) {
  return (
    <section className={styles.section}>
      {strategy && (
        <p className={styles.strategy}>
          <Sparkles size={16} /> <span><b>Gemini’s strategy:</b> {strategy}</span>
        </p>
      )}
      {items.length === 0 ? (
        <p className={styles.empty}>
          None of the AI’s suggestions could be verified in the movie database. Try regenerating or changing your choices.
        </p>
      ) : (
        <div className={styles.grid}>
          {items.map((item) => (
            <RecommendationCard key={item.imdbId} item={item} />
          ))}
        </div>
      )}
      <p className={styles.note}>
        Every title above was checked against OMDb. Ratings are official IMDb ratings; “AI match” is a score generated by
        Gemini, not an official rating.
        {dropped > 0 && ` ${dropped} suggestion${dropped === 1 ? '' : 's'} couldn’t be verified and ${dropped === 1 ? 'was' : 'were'} hidden.`}
      </p>
      {onRegenerate && (
        <div className={styles.actions}>
          <button onClick={onRegenerate} disabled={loading}>
            <RefreshCw size={16} className={loading ? styles.spin : ''} /> {loading ? 'Finding…' : 'Regenerate'}
          </button>
        </div>
      )}
    </section>
  )
}
